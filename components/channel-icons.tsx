/**
 * Returns null for a channel with no known mark, so a new entry in site.ts
 * degrades to a label instead of rendering an empty box.
 */
export function ChannelIcon({ id, className }: { id: string; className?: string }) {
  const mark = MARKS[id]
  if (!mark) return null

  return (
    <svg
      viewBox={mark.viewBox}
      className={className}
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
    >
      {mark.paths}
    </svg>
  )
}

export function hasChannelIcon(id: string): boolean {
  return id in MARKS
}
